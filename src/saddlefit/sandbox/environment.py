"""Environment images: the sandbox image plus one repository's dependencies (B11, B17).

Mining, the student and the evaluator run a repository's tests in the sandbox, which has no
network, so the dependencies must already be in the image. They are installed into a derived
image in a separate build step, which may use the network; runs never do. There is one image
per repository, built from its current dependency files and tagged with a hash of them and of
the base image, so an unchanged repository reuses the image it already has.

The dependency files are the repository owner's own, and installing them runs their build
hooks with network access, exactly as installing the project by hand would. The student never
touches this step: it only sees the finished image, from a container with no network. The
build runs under the sandbox's memory limit and an HTTP timeout; the Docker API offers no CPU
cap or daemon-side deadline for a build.
"""

from __future__ import annotations

import hashlib
import shutil
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Final, Literal

from pydantic import BaseModel, ConfigDict

from saddlefit.config import SandboxConfig
from saddlefit.sandbox.container import MIN_MEMORY_BYTES, SandboxError, memory_bytes

ENVIRONMENT_SCHEMA_VERSION: Final = 1
REQUIREMENTS_GLOBS: Final = ("requirements*.txt", "requirements/*.txt")
# seconds the Docker API may stay silent during a build before the client gives up
BUILD_TIMEOUT_S: Final = 1800
Source = Literal["uv.lock", "requirements", "pyproject"]


class EnvironmentRecord(BaseModel):
    """``.saddlefit/environment.json``: which image holds this repository's dependencies."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal[1]
    base_image: str
    base_id: str
    image: str
    dependencies: str  # sha256 over the base image id and the dependency files
    built_at: datetime


@dataclass(frozen=True)
class Dependencies:
    """The files that define a repository's environment, relative to its root."""

    source: Source
    files: tuple[str, ...]


def find_dependencies(repo: Path) -> Dependencies | None:
    """The repository's dependency files, preferring a lock file; ``None`` when it has none."""
    if (repo / "uv.lock").is_file() and (repo / "pyproject.toml").is_file():
        return Dependencies("uv.lock", ("pyproject.toml", "uv.lock"))
    requirements = sorted(
        {p.relative_to(repo).as_posix() for g in REQUIREMENTS_GLOBS for p in repo.glob(g)}
    )
    if requirements:
        return Dependencies("requirements", tuple(requirements))
    if (repo / "pyproject.toml").is_file():
        return Dependencies("pyproject", ("pyproject.toml",))
    return None


def fingerprint(repo: Path, deps: Dependencies, base_id: str) -> str:
    """A hash over the base image and every dependency file, names and contents."""
    digest = hashlib.sha256(base_id.encode())
    for rel in deps.files:
        digest.update(b"\0" + rel.encode() + b"\0")
        digest.update((repo / rel).read_bytes())
    return digest.hexdigest()


def image_tag(project: str, dependencies_hash: str) -> str:
    name = "".join(c if c.isalnum() or c in "._-" else "-" for c in project.lower()).strip("-")
    return f"saddlefit-env-{name or 'project'}:{dependencies_hash[:16]}"


def dockerfile(base_image: str, deps: Dependencies) -> str:
    """Install the dependencies as root, then hand the image back to the sandbox user."""
    if deps.source == "uv.lock":
        install = (
            "pip install --no-cache-dir uv"
            " && uv export --frozen --all-groups --no-emit-project --no-hashes"
            " -o /tmp/deps/requirements.lock"
            " && pip install --no-cache-dir -r /tmp/deps/requirements.lock"
        )
    elif deps.source == "requirements":
        install = " && ".join(
            f"pip install --no-cache-dir -r /tmp/deps/{rel}" for rel in deps.files
        )
    else:
        install = (
            "pip install --no-cache-dir uv"
            " && uv pip compile --all-extras /tmp/deps/pyproject.toml"
            " -o /tmp/deps/requirements.lock"
            " && pip install --no-cache-dir -r /tmp/deps/requirements.lock"
        )
    return (
        "# Generated by saddlefit: the sandbox image plus this repository's dependencies.\n"
        f"FROM {base_image}\n"
        "USER root\n"
        "COPY deps/ /tmp/deps/\n"
        f"RUN cd /tmp/deps && {install} && rm -rf /tmp/deps\n"
        "USER student\n"
    )


def ensure_environment(
    docker_client: Any,
    base_image: str,
    repo: Path,
    project: str,
    limits: SandboxConfig | None = None,
) -> EnvironmentRecord | None:
    """The environment image for ``repo``, built only when no image matches its dependencies.

    Returns ``None`` when the repository declares no dependencies: the base image is enough.
    The build runs under ``limits``' memory limit, the sandbox's by default.
    """
    memory = memory_bytes((limits or SandboxConfig()).memory)
    if memory < MIN_MEMORY_BYTES:  # Docker reads 0 as no limit at all
        raise SandboxError(f"memory limit below Docker's 6m minimum: {memory} bytes")
    deps = find_dependencies(repo)
    if deps is None:
        return None
    try:
        base_id = str(docker_client.images.get(base_image).id)
    except Exception as exc:
        raise SandboxError(f"sandbox image {base_image} is not available: {exc}") from exc
    dependencies_hash = fingerprint(repo, deps, base_id)
    tag = image_tag(project, dependencies_hash)
    record = EnvironmentRecord(
        schema_version=ENVIRONMENT_SCHEMA_VERSION,
        base_image=base_image,
        base_id=base_id,
        image=tag,
        dependencies=dependencies_hash,
        built_at=datetime.now(UTC),
    )
    try:
        docker_client.images.get(tag)
        return record  # already built for exactly these dependencies
    except Exception:  # noqa: S110 - a missing image is the normal case: build it below
        pass
    with tempfile.TemporaryDirectory(prefix="saddlefit-env-") as tmp:
        context = Path(tmp)
        for rel in deps.files:
            target = context / "deps" / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(repo / rel, target)
        (context / "Dockerfile").write_text(dockerfile(base_image, deps), encoding="utf-8")
        try:
            with _without_registry_credentials(docker_client):
                docker_client.images.build(
                    path=str(context),
                    tag=tag,
                    rm=True,
                    pull=False,
                    timeout=BUILD_TIMEOUT_S,
                    container_limits={"memory": memory, "memswap": memory},
                )
        except Exception as exc:
            raise SandboxError(f"building the environment image {tag} failed: {exc}") from exc
    return record


@contextmanager
def _without_registry_credentials(docker_client: Any) -> Iterator[None]:
    """Build without sending registry credentials, which this build never needs.

    docker-py attaches the credentials of every configured registry to a build, asking each
    credential helper in turn; one broken helper (say, an expired cloud login) then fails a
    build that pulls nothing. The base image is local and ``pull=False``, so none are sent.
    """
    api = getattr(docker_client, "api", None)
    if api is None or not hasattr(api, "_set_auth_headers"):
        yield
        return
    own = api.__dict__.get("_set_auth_headers")  # an override someone else already set
    api._set_auth_headers = lambda headers: None
    try:
        yield
    finally:
        if own is None:
            del api._set_auth_headers  # back to the class's method
        else:
            api._set_auth_headers = own
